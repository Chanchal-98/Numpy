import numpy as np

values = np.array([4, 6, 8, 10])

# Square root
result = np.sqrt(values)
print("Square: ", result)

# Exponential
result = np.exp(values)
print("Exponential: ",result)

# Natural alogrithm
result = np.log(values)
print("Natural algorithm: ",result)

# Sum
result = np.sum(values)
print("Sum: ",result)

# Cumulative sum
result = np.cumsum(values)
print("Cumulative sum: ",result)