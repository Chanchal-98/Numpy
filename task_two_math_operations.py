import numpy as np

A = np.array([10,20,30,40])
B = np.array([1,2,3,4])

# Addition
print("Addition:", np.add(A + B))


# Subtraction
print("Substraction: ", np.subtract(A - B))

# Multiplication
print("Multiplication: ",A * B)

# Division
print("Division: ",A / B)

# Power
print("Power: ",A ** B)

